/** ตัวสุ่มแบบกำหนด seed ได้ — ตัวเดียวกับที่ genesis ใช้ (mulberry32)
 *  มีไว้เพื่อให้ `npm run balance` เล่นซ้ำได้ผลเดิมทุกครั้ง
 *
 *  เดิม balance.ts ใช้ `() => 0.5` คงที่เพื่อให้ผลซ้ำได้ ซึ่งได้ผลซ้ำจริง
 *  แต่แลกมาด้วยการที่ทุกอย่างที่ตัดสินด้วยการสุ่มกลายเป็นตายตัวไปด้วย
 *  โอกาสโดนครูปกครองจับสูงสุดในเกมคือ 0.34 ซึ่งต่ำกว่า 0.5 เสมอ
 *  แปลว่า `rnd() > chance` เป็นจริงทุกครั้ง ฝ่ายปกครองทั้งระบบจึงไม่เคยทำงานในเทสต์เลย */
export type Rnd = () => number;

export function mulberry32(seed: number): Rnd {
  let a = seed | 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v);
